// Tables are read without RLS: every referenced id must belong to the org.
async function checkRefs(db: Db, orgId: string, r: { position_id?: string | null; location_id?: string | null; event_id?: string | null; staff?: string[]; positions?: string[] }) {
  const ids = (v: (string | null | undefined)[]) => [...new Set(v.filter((x): x is string => !!x))]
  const pos = ids([r.position_id, ...(r.positions ?? [])])
  const staff = ids(r.staff ?? [])
  const none = Promise.resolve({ data: [] as { id: string }[] })
  const [p, l, e, s] = await Promise.all([
    pos.length ? db.from("positions").select("id").eq("org_id", orgId).in("id", pos) : none,
    r.location_id ? db.from("locations").select("id").eq("org_id", orgId).eq("id", r.location_id) : none,
    r.event_id ? db.from("events").select("id").eq("org_id", orgId).eq("id", r.event_id).is("deleted_at", null) : none,
    staff.length ? db.from("staff").select("id").eq("org_id", orgId).in("id", staff) : none,
  ])
  const bad = [
    (p.data?.length ?? 0) < pos.length && "position",
    r.location_id && !l.data?.length && "location_id",
    r.event_id && !e.data?.length && "event_id",
    (s.data?.length ?? 0) < staff.length && "staff",
  ].filter(Boolean)
  if (bad.length) throw new ApiError(422, "invalid_reference", `Unknown ${bad.join(", ")} in this organisation.`)
}
async function getShift(db: Db, orgId: string, id: string) {
  const { data } = await db.from("shifts").select(SHIFT_COLS).eq("id", id).eq("org_id", orgId).maybeSingle()
  if (!data) throw notFound()
  return data
}
async function getOne<T extends "staff" | "positions" | "shift_series">(db: Db, table: T, cols: string, orgId: string, id: string) {
  const { data } = await db.from(table as "staff").select(cols).eq("id", id).eq("org_id", orgId).maybeSingle()
  if (!data) throw notFound()
  return data as unknown as Record<string, unknown>
}

