const SeriesFields = {
  name: z.string().trim().max(100).nullable(),
  position_id: uuid.nullable(),
  location_id: uuid.nullable(),
  weekdays: z.array(z.number().int().min(1).max(7)).min(1).max(7),
  every_weeks: z.number().int().min(1).max(8),
  start_date: day,
  end_date: day.nullable(),
  start_time: time,
  end_time: time.describe("HH:MM; earlier than start_time = ends the next day"),
  needed: z.number().int().min(1).max(100),
  default_staff: z.array(uuid).max(100).describe("Staff ids, always assigned"),
}
type SeriesIn = { [K in keyof typeof SeriesFields]: z.infer<(typeof SeriesFields)[K]> }
function checkSeries(s: SeriesIn) {
  if (s.end_date && s.end_date < s.start_date) throw new ApiError(422, "invalid_input", "end_date is before start_date.")
  if (s.start_time === s.end_time) throw new ApiError(422, "invalid_input", "start_time and end_time are equal.")
  if (!s.name?.trim() && !s.position_id) throw new ApiError(422, "invalid_input", "Give a name or a position.")
}
const hhmm = (t: string) => t.slice(0, 5)
const thisMonth = () => new Date().toLocaleDateString("sv-SE", { timeZone: "Europe/Berlin" }).slice(0, 7)

